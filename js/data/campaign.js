  /* ------------------------------------------------------------ 进度存档 */
  var KEY = 'naval.campaign.v1';

  /** file:// 或隐私模式下 localStorage 可能直接抛异常 */
  function store() {
    try {
      if (typeof window !== 'undefined' && window.localStorage) return window.localStorage;
    } catch (e) { /* ignore */ }
    return null;
  }

  var memory = null;   // 存不了的时候退化成内存

  var Campaign = {
    chapters: function () { return CHAPTERS; },

    byId: function (id) {
      for (var i = 0; i < CHAPTERS.length; i++) if (CHAPTERS[i].id === id) return CHAPTERS[i];
      return null;
    },

    /** 这个场景属于哪一章（自由选择里的场景可能不在战役线上） */
    byScenario: function (scenarioId) {
      for (var i = 0; i < CHAPTERS.length; i++) {
        if (CHAPTERS[i].scenario === scenarioId) return CHAPTERS[i];
      }
      return null;
    },

    indexOfScenario: function (scenarioId) {
      for (var i = 0; i < CHAPTERS.length; i++) {
        if (CHAPTERS[i].scenario === scenarioId) return i;
      }
      return -1;
    },

    /** 下一章（按战役线顺序） */
    nextOf: function (chapterId) {
      for (var i = 0; i < CHAPTERS.length; i++) {
        if (CHAPTERS[i].id === chapterId) return CHAPTERS[i + 1] || null;
      }
      return null;
    },

    /* ---------------------------------------------------------- 进度 */
    load: function () {
      if (memory) return memory;
      var raw = null;
      var s = store();
      if (s) { try { raw = s.getItem(KEY); } catch (e) { raw = null; } }
      var data = { cleared: {}, best: {} };
      if (raw) {
        try {
          var o = JSON.parse(raw);
          if (o && o.cleared) data.cleared = o.cleared;
          if (o && o.best) data.best = o.best;
        } catch (e) { /* 存档坏了就当没有 */ }
      }
      memory = data;
      return data;
    },

    save: function (data) {
      memory = data;
      var s = store();
      if (!s) return false;
      try { s.setItem(KEY, JSON.stringify(data)); return true; } catch (e) { return false; }
    },

    isCleared: function (chapterId) {
      return !!Campaign.load().cleared[chapterId];
    },

    /** 第 i 章是否解锁：第一章永远可玩，之后要求上一章通关 */
    isUnlocked: function (i) {
      if (i <= 0) return true;
      var prev = CHAPTERS[i - 1];
      return !!Campaign.load().cleared[prev.id];
    },

    /** 记一次通关（result: win / loss / draw） */
    markCleared: function (chapterId, result) {
      var d = Campaign.load();
      d.cleared[chapterId] = true;
      if (result) {
        var prev = d.best[chapterId];
        if (!prev || result === 'win') d.best[chapterId] = result;
      }
      Campaign.save(d);
      return d;
    },

    clearedCount: function () {
      var d = Campaign.load(), n = 0;
      for (var i = 0; i < CHAPTERS.length; i++) if (d.cleared[CHAPTERS[i].id]) n++;
      return n;
    },

    /** 下一个还没通关的章节（战役线的「继续」位置） */
    nextPlayable: function () {
      var d = Campaign.load();
      for (var i = 0; i < CHAPTERS.length; i++) {
        if (!d.cleared[CHAPTERS[i].id] && Campaign.isUnlocked(i)) return CHAPTERS[i];
      }
      return CHAPTERS[CHAPTERS.length - 1];
    },

    reset: function () {
      Campaign.save({ cleared: {}, best: {} });
    }
  };

  N.Campaign = Campaign;
